('Política de Devoluções','politica-devolucoes','Devoluções e Livre Resolução

1. Compras à distância por consumidores
Quando uma compra efetuada na loja online esteja abrangida pelo regime dos contratos celebrados à distância, o consumidor dispõe, em regra, de 14 dias para exercer o direito de livre resolução sem necessidade de indicar motivo, nos termos do Decreto-Lei n.º 24/2014, de 14 de fevereiro.

O prazo e a forma de contagem dependem do tipo de contrato e da entrega efetuada. Existem exceções legais em que o direito de livre resolução não se aplica.

2. Como comunicar a devolução
A decisão deve ser comunicada à MDTech de forma inequívoca dentro do prazo aplicável. Pode utilizar a área de cliente/RMA ou enviar a comunicação para geral@mdtech.pt, identificando a encomenda, os artigos e os dados necessários para localizar a compra.

Após comunicar a livre resolução, o consumidor deve devolver os bens dentro do prazo legal aplicável. Antes do envio, recomendamos aguardar as instruções de devolução da MDTech para assegurar a correta identificação do processo.

3. Estado do artigo
O consumidor pode inspecionar o bem na medida necessária para determinar a sua natureza, características e funcionamento. Pode ser responsável pela depreciação resultante de manipulações que excedam o necessário para essa verificação.

O artigo deve ser devolvido devidamente acondicionado e, sempre que existam, com os elementos, acessórios e documentação que façam parte do produto. A ausência ou deterioração desses elementos será analisada à luz das regras legais aplicáveis e do eventual impacto no valor do bem.

4. Custos de devolução
Nos casos de livre resolução em que a lei determine que o custo direto da devolução é suportado pelo consumidor, esse custo fica a cargo do consumidor, salvo se a MDTech tiver acordado suportá-lo ou se a lei determinar solução diferente.

Esta regra não se confunde com os custos associados à reposição da conformidade de um bem abrangido pela garantia legal.

5. Reembolso
Nos termos legais, os pagamentos abrangidos pela livre resolução são reembolsados através do mesmo meio de pagamento utilizado na transação inicial, salvo acordo expresso em contrário e desde que o consumidor não incorra em custos. Quando aplicável, o reembolso inclui o custo da modalidade normal de entrega inicialmente disponibilizada pela MDTech, não sendo obrigatório reembolsar custos adicionais resultantes da escolha de uma modalidade de entrega mais onerosa.

A MDTech pode, nos casos previstos na lei, reter o reembolso até receber os bens devolvidos ou até o consumidor apresentar prova do respetivo envio.

6. Exceções legais
O direito de livre resolução tem exceções previstas na lei. Dependendo do caso, podem estar abrangidos, entre outros, bens confecionados de acordo com especificações do consumidor ou manifestamente personalizados, determinados bens selados que não sejam suscetíveis de devolução por motivos de proteção da saúde ou higiene quando abertos, gravações áudio/vídeo ou programas informáticos selados cujo selo tenha sido retirado e conteúdos digitais cuja execução se tenha iniciado nas condições legalmente previstas.

A mera abertura de uma embalagem de um componente informático não elimina automaticamente o direito de livre resolução; cada situação é analisada segundo a natureza do produto, a manipulação efetuada e as exceções efetivamente previstas na lei.

7. Produto com avaria ou falta de conformidade
Uma devolução por livre resolução é diferente de um pedido de garantia. Se o produto apresentar uma possível falta de conformidade, utilize RMA / Assistência e consulte a página Garantias.

