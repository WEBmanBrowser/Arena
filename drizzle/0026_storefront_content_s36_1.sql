('Garantias','garantias','Garantias, Conformidade e RMA

1. Garantia legal do consumidor
As compras efetuadas por consumidores beneficiam dos direitos legais de conformidade previstos no Decreto-Lei n.º 84/2021, de 18 de outubro. Para bens móveis novos adquiridos desde 1 de janeiro de 2022, a responsabilidade do profissional por faltas de conformidade manifestadas é, em regra, de três anos a contar da entrega, sem prejuízo das regras e exceções previstas na lei.

Estes direitos legais não são reduzidos por garantias comerciais ou garantias disponibilizadas pelo fabricante.

2. O que fazer quando existe um problema
Antes de enviar um equipamento, recomendamos que confirme ligações, alimentação, acessórios e, quando aplicável, atualizações ou procedimentos de diagnóstico indicados pelo fabricante.

Para iniciar um pedido junto da MDTech, utilize a área de cliente em RMA / Assistência ou contacte geral@mdtech.pt. Identifique a encomenda ou documento de compra, o artigo e descreva o problema com o máximo de detalhe possível.

3. Análise do equipamento
Após receção, o artigo pode ser sujeito a diagnóstico para confirmar a ocorrência comunicada e determinar o tratamento adequado. Sempre que o processo dependa do fabricante, distribuidor ou centro técnico autorizado, a MDTech acompanha o pedido e comunica ao cliente a evolução relevante.

A entrega de um equipamento para diagnóstico não significa, por si só, que a situação esteja abrangida pela garantia legal. Danos acidentais, utilização indevida ou outras causas não imputáveis a falta de conformidade podem ficar fora desse regime, sem prejuízo da análise concreta e dos direitos legalmente aplicáveis.

4. Soluções previstas na lei
Quando exista uma falta de conformidade abrangida pelo regime legal, podem aplicar-se, consoante os pressupostos previstos na lei, reparação ou substituição e, nas situações legalmente previstas, redução proporcional do preço ou resolução do contrato.

Quando a falta de conformidade se manifeste nos primeiros 30 dias após a entrega, a lei prevê um direito de rejeição nas condições legalmente estabelecidas.

A reparação de um bem móvel abrangida pelo regime legal pode conferir um período adicional de garantia de seis meses por cada reparação, até ao limite legal de quatro reparações, nos termos do Decreto-Lei n.º 84/2021.

